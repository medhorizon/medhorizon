import z from "zod"

/**
 * Capability policy for process-backed tools.
 *
 * The process boundary deals in logical capability IDs rather than raw
 * environment variable names.  A capability only becomes visible when all
 * three inputs agree: the one-shot execution request, the loaded skill's
 * declaration, and the current agent profile grant.  This module is kept
 * independent of Config/Skill so it can be used at both schema and spawn
 * boundaries without introducing a dependency cycle.
 */

